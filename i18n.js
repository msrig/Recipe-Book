const SUPPORTED_RECIPE_LANGS = ["ru", "en", "uk"];
const DEFAULT_RECIPE_LANG = "en";

function getRecipeLang() {
  const params = new URLSearchParams(window.location.search);
  const fromUrl = params.get("lang");
  if (SUPPORTED_RECIPE_LANGS.includes(fromUrl)) return fromUrl;

  const saved = localStorage.getItem("recipe_lang");
  if (SUPPORTED_RECIPE_LANGS.includes(saved)) return saved;

  return DEFAULT_RECIPE_LANG;
}

function setRecipeLang(lang) {
  if (!SUPPORTED_RECIPE_LANGS.includes(lang)) return;
  localStorage.setItem("recipe_lang", lang);
  window.recipeLang = lang;
  document.documentElement.lang = lang;
  applyRecipeTranslations();
  applyRuntimeTranslations(document.body);
  window.dispatchEvent(new CustomEvent("recipe-language-change", { detail: { lang } }));
}

function tRecipe(key) {
  const lang = window.recipeLang || getRecipeLang();
  return RECIPE_TRANSLATIONS[lang]?.[key] || RECIPE_TRANSLATIONS[DEFAULT_RECIPE_LANG][key] || key;
}

function recipeCategoryLabel(category) {
  const lang = window.recipeLang || getRecipeLang();
  return CATEGORY_LABELS[lang]?.[category] || category || "";
}

function recipeCountryLabel(country) {
  const lang = window.recipeLang || getRecipeLang();
  return COUNTRY_LABELS[lang]?.[country] || country || "";
}

function recipeTitle(recipe) {
  const lang = window.recipeLang || getRecipeLang();
  if (lang === "en" && recipe.titleEn) return recipe.titleEn;
  return recipe.title || recipe.titleEn || "";
}

function applyRecipeTranslations() {
  const lang = window.recipeLang || getRecipeLang();
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = tRecipe(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.setAttribute("placeholder", tRecipe(element.dataset.i18nPlaceholder));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", tRecipe(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.setAttribute("title", tRecipe(element.dataset.i18nTitle));
  });

  if (isAdminPage()) {
    document.title = translateRuntimeText(document.title);
  } else {
    const titleKey = document.body?.dataset.page === "recipe-detail" ? "meta.recipeTitle" : "meta.homeTitle";
    document.title = tRecipe(titleKey);
  }

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    const active = button.dataset.langOption === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function isAdminPage() {
  return window.location.pathname.startsWith("/admin/");
}

function translateRuntimeText(value) {
  const lang = window.recipeLang || getRecipeLang();
  if (!value) return value;

  const canonical = canonicalRuntimeText(value);
  if (canonical) {
    return runtimeTextForLang(canonical, lang);
  }

  const prefixed = canonicalPrefixText(value);
  if (prefixed) {
    const rest = prefixed.rest.replace(/^\s+/, "");
    const translatedRest = rest ? translateRuntimeText(rest) : "";
    return `${prefixTextForLang(prefixed.prefix, lang)}${translatedRest ? ` ${translatedRest}` : ""}`;
  }

  const deleteCategoryMatch = value.match(/^(?:Удалить категорию|Delete category|Видалити категорію) "(.+)"\?$/);
  if (deleteCategoryMatch) {
    const categoryLabel = translateRuntimeText(deleteCategoryMatch[1]);
    if (lang === "en") return `Delete category "${categoryLabel}"?`;
    if (lang === "uk") return `Видалити категорію "${categoryLabel}"?`;
    return `Удалить категорию "${categoryLabel}"?`;
  }

  const flagMatch = value.match(/^([\u{1F1E6}-\u{1F1FF}]{2})\s+(.+)$/u);
  if (flagMatch) {
    const translatedCountry = translateRuntimeText(flagMatch[2]);
    return `${flagMatch[1]} ${translatedCountry}`;
  }

  return value;
}

function canonicalRuntimeText(value) {
  if (ADMIN_TEXT_LABELS.en?.[value] || ADMIN_TEXT_LABELS.uk?.[value]) return value;

  const adminSource = Object.keys(ADMIN_TEXT_LABELS.en || {}).find(source =>
    ADMIN_TEXT_LABELS.en[source] === value || ADMIN_TEXT_LABELS.uk?.[source] === value
  );
  if (adminSource) return adminSource;

  const translationKey = Object.keys(RECIPE_TRANSLATIONS[DEFAULT_RECIPE_LANG]).find(key =>
    RECIPE_TRANSLATIONS[DEFAULT_RECIPE_LANG][key] === value ||
    RECIPE_TRANSLATIONS.en?.[key] === value ||
    RECIPE_TRANSLATIONS.uk?.[key] === value
  );
  if (translationKey) return `recipe:${translationKey}`;

  const categorySource = Object.keys(CATEGORY_LABELS.ru).find(source =>
    source === value ||
    CATEGORY_LABELS.ru[source] === value ||
    CATEGORY_LABELS.uk?.[source] === value
  );
  if (categorySource) return `category:${categorySource}`;

  const countrySource = Object.keys(COUNTRY_LABELS.ru).find(source =>
    source === value ||
    COUNTRY_LABELS.ru[source] === value ||
    COUNTRY_LABELS.uk?.[source] === value
  );
  if (countrySource) return `country:${countrySource}`;

  return null;
}

function runtimeTextForLang(canonical, lang) {
  if (canonical.startsWith("recipe:")) {
    const key = canonical.slice(7);
    return RECIPE_TRANSLATIONS[lang]?.[key] || RECIPE_TRANSLATIONS[DEFAULT_RECIPE_LANG][key] || canonical;
  }

  if (canonical.startsWith("category:")) {
    const category = canonical.slice(9);
    return CATEGORY_LABELS[lang]?.[category] || category;
  }

  if (canonical.startsWith("country:")) {
    const country = canonical.slice(8);
    return COUNTRY_LABELS[lang]?.[country] || country;
  }

  return ADMIN_TEXT_LABELS[lang]?.[canonical] || canonical;
}

function canonicalPrefixText(value) {
  const sourcePrefixes = ADMIN_PREFIX_LABELS.en.map(([source]) => source);
  for (const source of sourcePrefixes) {
    const translatedEn = ADMIN_PREFIX_LABELS.en.find(([from]) => from === source)?.[1];
    const translatedUk = ADMIN_PREFIX_LABELS.uk.find(([from]) => from === source)?.[1];
    const matched = [source, translatedEn, translatedUk].filter(Boolean).find(prefix => value.startsWith(prefix));
    if (matched) return { prefix: source, rest: value.slice(matched.length) };
  }

  return null;
}

function prefixTextForLang(prefix, lang) {
  if (lang === DEFAULT_RECIPE_LANG) return prefix;
  return ADMIN_PREFIX_LABELS[lang]?.find(([source]) => source === prefix)?.[1] || prefix;
}

function translateTextNode(node) {
  const original = node.nodeValue;
  const trimmed = original.replace(/\s+/g, " ").trim();
  if (!trimmed) return;

  const translated = translateRuntimeText(trimmed);
  if (translated === trimmed) return;

  node.nodeValue = original.replace(trimmed, translated);
}

function shouldSkipTextNode(node) {
  const parent = node.parentElement;
  if (!parent) return true;
  return ["SCRIPT", "STYLE", "TEXTAREA", "INPUT"].includes(parent.tagName);
}

function translateAttributes(element) {
  ["placeholder", "aria-label", "title", "alt"].forEach(attr => {
    const value = element.getAttribute(attr);
    const translated = translateRuntimeText(value);
    if (translated && translated !== value) {
      element.setAttribute(attr, translated);
    }
  });
}

function applyRuntimeTranslations(root = document.body) {
  if (!root) return;

  if (root.nodeType === Node.ELEMENT_NODE) {
    translateAttributes(root);
  }

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
    {
      acceptNode(node) {
        if (node.nodeType === Node.TEXT_NODE) {
          return shouldSkipTextNode(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node);
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      translateAttributes(node);
    }
  }
}

function installRuntimeTranslator() {
  if (!isAdminPage()) return;

  const observer = new MutationObserver(mutations => {
    observer.disconnect();
    mutations.forEach(mutation => {
      mutation.addedNodes.forEach(node => {
        if (node.nodeType === Node.TEXT_NODE && !shouldSkipTextNode(node)) {
          translateTextNode(node);
        } else if (node.nodeType === Node.ELEMENT_NODE) {
          applyRuntimeTranslations(node);
        }
      });
    });
    observer.observe(document.body, { childList: true, subtree: true });
  });

  observer.observe(document.body, { childList: true, subtree: true });
}

function installDialogTranslator() {
  if (window.__recipeDialogsTranslated) return;
  window.__recipeDialogsTranslated = true;

  const nativeAlert = window.alert.bind(window);
  const nativeConfirm = window.confirm.bind(window);

  window.alert = message => nativeAlert(translateRuntimeText(String(message)));
  window.confirm = message => nativeConfirm(translateRuntimeText(String(message)));
}

function createLanguageSwitcher() {
  const switcher = document.createElement("div");
  switcher.className = "language-switcher admin-language-switcher";
  switcher.setAttribute("aria-label", "Language");
  switcher.innerHTML = `
    <button type="button" data-lang-option="ru">RU</button>
    <button type="button" data-lang-option="en">EN</button>
    <button type="button" data-lang-option="uk">UA</button>
  `;
  return switcher;
}

function ensureLanguageSwitcher() {
  if (!isAdminPage() || document.querySelector(".admin-language-switcher")) return;

  const switcher = createLanguageSwitcher();
  const topBarRight = document.querySelector(".top-bar-right");
  if (topBarRight) {
    topBarRight.prepend(switcher);
    return;
  }

  switcher.classList.add("floating-language-switcher");
  document.body.appendChild(switcher);
}

function initRecipeI18n() {
  window.recipeLang = getRecipeLang();
  ensureLanguageSwitcher();
  applyRecipeTranslations();
  applyRuntimeTranslations(document.body);
  installRuntimeTranslator();
  installDialogTranslator();

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    button.addEventListener("click", () => setRecipeLang(button.dataset.langOption));
  });
}

document.addEventListener("DOMContentLoaded", initRecipeI18n);
