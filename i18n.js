const SUPPORTED_RECIPE_LANGS = ["ru", "en", "uk"];
const DEFAULT_RECIPE_LANG = "ru";

function getRecipeLang() {
  const params = new URLSearchParams(window.location.search);
  const fromUrl = params.get("lang");
  if (SUPPORTED_RECIPE_LANGS.includes(fromUrl)) return fromUrl;

  const saved = localStorage.getItem("recipe_lang");
  if (SUPPORTED_RECIPE_LANGS.includes(saved)) return saved;

  const browserLang = (navigator.language || "").slice(0, 2).toLowerCase();
  return SUPPORTED_RECIPE_LANGS.includes(browserLang) ? browserLang : DEFAULT_RECIPE_LANG;
}

function setRecipeLang(lang) {
  if (!SUPPORTED_RECIPE_LANGS.includes(lang)) return;
  localStorage.setItem("recipe_lang", lang);
  window.recipeLang = lang;
  document.documentElement.lang = lang;
  applyRecipeTranslations();
  window.dispatchEvent(new CustomEvent("recipe-language-change", { detail: { lang } }));
}

function tRecipe(key) {
  const lang = window.recipeLang || getRecipeLang();
  return RECIPE_TRANSLATIONS[lang]?.[key] || RECIPE_TRANSLATIONS[DEFAULT_RECIPE_LANG][key] || key;
}

function recipeCategoryLabel(category) {
  const lang = window.recipeLang || getRecipeLang();
  return CATEGORY_LABELS[lang]?.[category] || category || "";
}

function recipeCountryLabel(country) {
  const lang = window.recipeLang || getRecipeLang();
  return COUNTRY_LABELS[lang]?.[country] || country || "";
}

function recipeTitle(recipe) {
  const lang = window.recipeLang || getRecipeLang();
  if (lang === "en" && recipe.titleEn) return recipe.titleEn;
  return recipe.title || recipe.titleEn || "";
}

function applyRecipeTranslations() {
  const lang = window.recipeLang || getRecipeLang();
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = tRecipe(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.setAttribute("placeholder", tRecipe(element.dataset.i18nPlaceholder));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", tRecipe(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.setAttribute("title", tRecipe(element.dataset.i18nTitle));
  });

  const titleKey = document.body?.dataset.page === "recipe-detail" ? "meta.recipeTitle" : "meta.homeTitle";
  document.title = tRecipe(titleKey);

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    const active = button.dataset.langOption === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function initRecipeI18n() {
  window.recipeLang = getRecipeLang();
  applyRecipeTranslations();

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    button.addEventListener("click", () => setRecipeLang(button.dataset.langOption));
  });
}

document.addEventListener("DOMContentLoaded", initRecipeI18n);
